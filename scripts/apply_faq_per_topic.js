const FAQ_CSS_BLOCK = `
.faq-section{max-width:880px;margin:3rem auto 2rem;padding:0 1.5rem;}
.faq-section h2{font-size:1.1rem;font-weight:500;letter-spacing:.04em;text-align:center;color:var(--white);margin:0 0 1.5rem;}
.faq-list{max-width:760px;margin:.5rem auto 0;}
.faq-item{border-top:1px solid var(--border);padding:1.15rem 0;}
.faq-item:last-child{border-bottom:1px solid var(--border);}
.faq-q{font-weight:500;color:var(--white);font-size:.98rem;line-height:1.6;margin:0 0 .55rem;}
.faq-q::before{content:"Q. ";color:var(--gold);font-weight:700;}
.faq-a{font-weight:300;color:var(--muted);font-size:.9rem;line-height:1.85;margin:0;}
.faq-a::before{content:"A. ";color:var(--gold);font-weight:500;}`;

function buildFaqJsonLd(questions) {
  const mainEntity = questions.map(({ q, a }) => ({
    '@type': 'Question',
    name: q,
    acceptedAnswer: { '@type': 'Answer', text: a },
  }));
  return `<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity })}</script>`;
}

function buildVisibleFaq(title, questions) {
  const items = questions.map(({ q, a }) => `    <div class="faq-item">
      <p class="faq-q">${q}</p>
      <p class="faq-a">${a}</p>
    </div>`).join('\n');
  return `<section class="faq-section" id="faq">
  <h2>${title} よくある質問</h2>
  <div class="faq-list">
${items}
  </div>
</section>
`;
}

function applyOne(filename, conf) {
  const filePath = path.join(FEATURES_DIR, filename);
  let html = fs.readFileSync(filePath, 'utf8');

  if (html.includes('<p class="faq-q">') || html.includes('"@type":"FAQPage"')) {
    return { filename, skipped: 'already_has_faq' };
  }

  // 1. CSS 挿入: .shop-name { ... } の行の直後
  const cssAnchor = '.shop-name{font-family:\'Cormorant Garamond\',serif;font-size:1.2rem;font-weight:400;color:var(--white);margin-bottom:.3rem;}';
  if (!html.includes(cssAnchor)) return { filename, skipped: 'no_css_anchor' };
  html = html.replace(cssAnchor, cssAnchor + FAQ_CSS_BLOCK);

  // 2. JSON-LD 挿入: 末尾の ItemList ブロック直後
  const itemListMatch = html.match(/(<script type="application\/ld\+json">\{"@context":"https:\/\/schema\.org","@type":"ItemList"[^]*?<\/script>)\s*(<\/div>)/);
  if (!itemListMatch) return { filename, skipped: 'no_itemlist_anchor' };
  const faqJsonLd = buildFaqJsonLd(conf.questions);
  html = html.replace(itemListMatch[0], itemListMatch[1] + '\n  ' + faqJsonLd + '\n' + itemListMatch[2]);

  // 3. 可視 FAQ 挿入: 上で置換した </div> の直後
  const visibleFaq = buildVisibleFaq(conf.title, conf.questions);
  // </div> 直後に挿入（最初に出現する footer 直前を狙う）
  html = html.replace(/<\/div>\s*\n\s*<footer>/, '</div>\n\n' + visibleFaq + '\n<footer>');

  if (DRY) {
    console.log(`[DRY] ${filename}: FAQ ${conf.questions.length}問追加予定`);
  } else {
    fs.writeFileSync(filePath, html);
    console.log(`✅ ${filename}: FAQ ${conf.questions.length}問追加`);
  }
  return { filename, applied: conf.questions.length };
}

function main() {
  let applied = 0, skipped = 0;
  for (const [filename, conf] of Object.entries(FAQ_CONTENT)) {
    const r = applyOne(filename, conf);
    if (r.applied) applied++;
    else { console.log(`⏭ ${filename}: ${r.skipped}`); skipped++; }
  }
  console.log(`\n${DRY ? '[DRY] ' : ''}適用: ${applied} / スキップ: ${skipped}`);
}

main();
