'use strict';
/**
 * area_label.js — 店舗ページ <title> 用のエリア表記正規化
 *
 * 背景（ISSUE-072・GSC 実データ）: 店舗ページのタイトルが
 *   `${店名}（${エリア}・${ジャンル}）| NAGOYA BITES`
 * の形で、エリアにホットペッパー由来の冗長なクラスタ表記
 *   「栄(ミナミ)/矢場町/大須/上前津」「名古屋（名古屋駅/西区/中村区）」等
 * をそのまま使っていた。Google の検索結果はタイトルを約30字で切るため、
 * 店名の直後にこの長いエリア群が入ると「店名が途中で切れる／エリアがノイズ化」し、
 * CTR を大きく下げていた（例: National Bakery ページは 840表示・CTR1.2%・タイトル77字）。
 *
 * この関数は **タイトル表示専用** の短いエリアラベルを返す。
 * データ（LOCAL_STORES / stores.json）の「エリア」値そのものは変更しない。
 *
 * 方針: 既知の冗長クラスタだけを明示マップで簡潔化し、それ以外は原文パススルー
 *       （clever なパースで想定外の文字列を壊さないための安全設計）。
 */

// 既知の冗長エリアクラスタ → 検索意図に効く簡潔ラベル（代表2エリア程度）
const CLUSTER_MAP = {
  '名古屋（名古屋駅/西区/中村区）': '名駅',
  '栄ｷﾀ錦/伏見丸の内/泉/東桜/新栄': '栄・伏見',
  '栄(ミナミ)/矢場町/大須/上前津': '栄・矢場町',
  '大曽根･千種･今池･池下･守山区': '千種・大曽根',
  '緑区・南区・天白区・瑞穂区': '天白・瑞穂',
  '本山・覚王山・藤が丘': '覚王山・本山',
  '金山・神宮前・熱田区': '金山',
  '鶴舞・八事・御器所': '鶴舞・八事',
  '中川区・港区': '中川・港',
};

/**
 * タイトル表示用の簡潔なエリアラベルを返す。
 * @param {string} area 店舗データの「エリア」値（原文）
 * @returns {string} タイトルに載せる短いラベル
 */
function titleAreaLabel(area) {
  const a = (area || '').trim();
  if (!a) return '';
  if (CLUSTER_MAP[a]) return CLUSTER_MAP[a];
  // 未知でも区切り記号（/・･）を4つ以上含む＝クラスタと判断できる場合の保険:
  // 先頭トークンだけを採用（駅名/主要エリアが先頭に来る規約のため）。
  const tokens = a.split(/[\/・･]/).filter(Boolean);
  if (tokens.length >= 4) return tokens[0];
  return a; // 既に簡潔（栄 / 名古屋駅 / 金山 / 大須 等）はそのまま
}

module.exports = { titleAreaLabel, CLUSTER_MAP };
