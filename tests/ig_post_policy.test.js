test('落とすべき投稿を落とす', () => {
  for (const c of REJECT_CASES) {
    const r = c.evidence !== undefined
      ? judgePost(c.evidence, { storeName: c.store })
      : judge(c.caption, c.store);
    assert.equal(r.verdict, c.expect, `${c.name}\n  期待=${c.expect} 実際=${r.verdict} (${r.reason})\n  理由: ${c.why}`);
    assert.equal(r.ok, false, `${c.name}: ok は false であるべき`);
  }
});

test('通すべき投稿を通す（正直な投稿を巻き込まない）', () => {
  for (const c of PASS_CASES) {
    const r = judge(c.caption, c.store);
    assert.equal(r.ok, true, `${c.name}\n  実際=${r.verdict} (${r.reason})`);
  }
});

test('ハッシュタグは採点対象から外れる（事故の中核）', () => {
  // #焼肉 だけを根拠に料理投稿と判定されてはいけない
  const body = captionBody('今月もよろしくお願い致します #焼肉 #名古屋グルメ #焼肉やっちゃん');
  assert.ok(!body.includes('焼肉'), `ハッシュタグが本文に残っている: "${body}"`);
  assert.ok(!body.includes('名古屋グルメ'));
});

test('店名は採点対象から外れる（店名の料理語が中身の説明に化けるのを防ぐ）', () => {
  // 逐語一致
  const a = stripStoreName('鮮魚とおばんざい浜金 池下店です！本日のおすすめ', '鮮魚とおばんざい浜金 池下店');
  assert.ok(!a.includes('鮮魚'), `店名が剥がれていない: "${a}"`);

  // カタカナ/ひらがなの表記ゆれは吸収する
  const b = stripStoreName('本日は焼肉ホルえもんへ', '焼肉ほるえもん');
  assert.ok(!/ホルえもん/.test(b), `表記ゆれを吸収できていない: "${b}"`);

  // 限界の明示: 登録名と投稿中の表記が構造的に違う場合は剥がせない。
  // ここを取り繕って部分一致で剥がすと、本文中の本物の料理語まで消えて
  // 良い投稿を落とす副作用が出るため、剥がせないことを既知の限界として固定する。
  const c = stripStoreName('昭和焼肉ホルえもん名駅本店をご愛顧', '焼肉酒場ほるえもん');
  assert.ok(c.includes('焼肉'), '限界ケースの挙動が変わった（意図的なら期待値を更新すること）');
});

test('本文の実質文字数はハッシュタグ・絵文字・記号を数えない', () => {
  assert.equal(bodyLength(captionBody('#a #b #c 😀😀😀 ・・・')), 0);
  assert.ok(bodyLength(captionBody('今日のおばんざいです #和食')) >= 10);
});

test('判定は data/ig_post_policy.json の語彙だけで決まる（実装に閾値を埋めない）', () => {
  const { loadPolicy } = require('../scripts/lib/ig_post_policy.js');
  const P = loadPolicy();
  assert.ok(P.thresholds && typeof P.thresholds.minBodyChars === 'number');
  assert.ok(P.soft_block && typeof P.soft_block.requires_strong === 'number');
  // hard_block のカテゴリは JSON 側だけで増やせる（判定器はキーを総なめする）
  for (const key of Object.keys(P.hard_block)) {
    if (key.startsWith('_')) continue;
    assert.ok(Array.isArray(P.hard_block[key]), `${key} は配列であるべき`);
  }
});
